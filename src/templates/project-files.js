function createPackageJson(projectName) {
  return JSON.stringify(
    {
      name: projectName,
      version: '1.0.0',
      type: 'module',
      main: 'src/main.ts',
      scripts: {
        start: 'node --enable-source-maps dist/bundle.cjs',
        dev: 'node kit-dev/build/dev.cjs',
        build: 'node kit-dev/build/esbuild.config.cjs',
        type: 'tsc --watch --noEmit',
        di: 'node kit-dev/di/install.cjs',
      },
      dependencies: {},
      devDependencies: {},
      engines: {
        node: '>=22',
      },
      license: 'MIT',
    },
    null,
    2,
  );
}

function createTsconfig() {
  return JSON.stringify(
    {
      compilerOptions: {
        target: 'ES2022',
        module: 'NodeNext',
        moduleResolution: 'NodeNext',
        rootDir: './src',
        outDir: './dist',
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        forceConsistentCasingInFileNames: true,
        types: ['node'],
      },
      include: ['src'],
    },
    null,
    2,
  );
}

